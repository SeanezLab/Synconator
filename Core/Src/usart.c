void huart3_try_send(uint8_t* msg, uint16_t msg_size)
{
	if (huart3_tx_complete == 1)
	{
		huart3_tx_complete = 0;
		HAL_StatusTypeDef st = HAL_UART_Transmit_DMA(&huart3, msg, msg_size);

		if (st != HAL_OK)
		{
			huart3_tx_complete = 1;
		}
	}
}

